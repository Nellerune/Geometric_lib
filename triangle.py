def area(a,h):
    '''
    Возрващает площадь треугольника

        Параметры:
            а (int): длина стороны основания треугольника 
            h (int): длина высоты, проведённой к a
        
        Возвращаемое число:
            a*h/2 - площадь треугольника - перемноженные a и h, поделённые на 2
    '''
    return a*h/2

def perimeter(a,b,c):
    '''
        Возрващает периметр треугольника
    
            Параметры:
                а (int): длина первой стороны 
                b (int): длина второй стороны
                c (int): длина третьей стороны
            
            Возвращаемое число:
                a+b+c - периметр треугольника - сумма a,b,c
        '''
    return a+b+c