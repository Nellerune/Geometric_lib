import math
'''Импортируем библиотеку math для числа пи'''

def area(r):
    ''' Принимает радиус круга r
    Возвращает площадь пи*r**2'''
    return math.pi * r * r


def perimeter(r):
    ''' Принимает радиус r
    Возвращает площадь пи*r*2'''
    return 2 * math.pi * r

def delit(r):
    return r / 2

