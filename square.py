
def area(a):
    '''
    Возрващает площадь квадрата

        Параметры:
            а (int): длина стороны квадрата
        
        Возвращаемое число:
            a*a - площадь квадрата - a умноженная на себя
    '''
    return a * a


def perimeter(a):
    '''
        Возрващает периметр квадрата
    
            Параметры:
                а (int): длина стороны
            
            Возвращаемое число:
                a*4 - периметр квадрата - a умноженное на 4
        '''
    return 4 * a
